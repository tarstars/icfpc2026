#!/usr/bin/env python3
"""Build `gpt_brackets_17` from the validated 24x25 candidate.

This is a component-body peephole, not a geometry or routing change:

* mismatch output: `>rM1+ sH` -> `>rM1+sH`;
* balanced-end output: `X  sH` -> `XsH`.

The moved sends stay strictly nearer to the output endpoint than to the state
endpoint. Every room border, man, pipe cell, endpoint, and pipe length remains
byte-for-byte in place. Platform submission is intentionally outside this
script.
"""

from __future__ import annotations

from pathlib import Path

from littleman.sim import Machine

from build_gpt_brackets_16 import build_gpt_brackets_16

HERE = Path(__file__).resolve().parent
ARTIFACT = HERE / "gpt_brackets_17.man"

OLD_MISMATCH = "|         >rM1+ sH   |"
NEW_MISMATCH = "|         >rM1+sH    |"
OLD_BALANCED = "|   >    M4W-XrX  sH1|"
NEW_BALANCED = "|   >    M4W-XrXsH  1|"


def _signature(text: str) -> dict:
    machine = Machine.parse(text)
    room_index = {id(room): i for i, room in enumerate(machine.rooms)}
    return {
        "rooms": [
            (room.top, room.left, room.bottom, room.right, room.kind)
            for room in machine.rooms
        ],
        "men": [
            (man.r, man.c, room_index[id(man.room)]) for man in machine.men
        ],
        "pipes": [
            (
                room_index[id(pipe.source)],
                room_index[id(pipe.dest)],
                tuple(pipe.cells),
            )
            for pipe in machine.pipes
        ],
    }


def build_gpt_brackets_17() -> str:
    base = build_gpt_brackets_16()
    if base.count(OLD_MISMATCH) != 1 or base.count(OLD_BALANCED) != 1:
        raise AssertionError("gpt_brackets_16 component text drifted")
    candidate = base.replace(OLD_MISMATCH, NEW_MISMATCH).replace(
        OLD_BALANCED, NEW_BALANCED
    )
    if _signature(candidate) != _signature(base):
        raise AssertionError("terminal-arm peephole changed room/pipe structure")
    rows = candidate.rstrip("\n").split("\n")
    if (max(map(len, rows)), len(rows)) != (24, 25):
        raise AssertionError("candidate box drifted")
    return candidate


def main() -> int:
    candidate = build_gpt_brackets_17()
    if ARTIFACT.exists() and ARTIFACT.read_text() != candidate:
        raise AssertionError(f"{ARTIFACT} differs from generated bytes")
    print(candidate, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
